package com.mycompany.ejerciciotickets;

/**
 *
 * @author Usuario
 */
public class Ticket {
    private String idTicket;
    private String estado;
    private String fechaReporte;
    private String coincidencia;

    /**
     * @return the idTicket
     */
    public String getIdTicket() {
        return idTicket;
    }

    /**
     * @param idTicket the idTicket to set
     */
    public void setIdTicket(String idTicket) {
        this.idTicket = idTicket;
    }

    /**
     * @return the estado
     */
    public String getEstado() {
        return estado;
    }

    /**
     * @param estado the estado to set
     */
    public void setEstado(String estado) {
        this.estado = estado;
    }

    /**
     * @return the fechaReporte
     */
    public String getFechaReporte() {
        return fechaReporte;
    }

    /**
     * @param fechaReporte the fechaReporte to set
     */
    public void setFechaReporte(String fechaReporte) {
        this.fechaReporte = fechaReporte;
    }

    /**
     * @return the coincidencia
     */
    public String getCoincidencia() {
        return coincidencia;
    }

    /**
     * @param coincidencia the coincidencia to set
     */
    public void setCoincidencia(String coincidencia) {
        this.coincidencia = coincidencia;
    }
    
    
}
